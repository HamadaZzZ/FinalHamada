package com.example.finalhamada.data.MyTaskTable; // مكان الواجهة داخل المشروع

import androidx.room.Dao; // يحول الواجهة إلى DAO داخل Room Database
import androidx.room.Insert; // يستخدم لإضافة بيانات إلى قاعدة البيانات
import androidx.room.Query; // يستخدم لتنفيذ أوامر SQL

import java.util.List; // لتخزين قائمة عناصر

/**
 * ============================================================
 * UserFoodQuery
 * ============================================================
 *
 * هذه الواجهة تعتبر DAO
 * الخاصة بجدول user_food_table.
 *
 * DAO اختصار لـ:
 * Data Access Object
 *
 * يعني:
 * واجهة مسؤولة عن
 * التواصل مع قاعدة البيانات.
 *
 * استخدمتها للتعامل مع:
 * - إضافة الطعام
 * - جلب جميع الأطعمة
 * - حذف الطعام
 *
 * Room يقوم تلقائيًا
 * بتحويل هذه الدوال
 * إلى SQL Queries حقيقية.
 */
@Dao
public interface UserFoodQuery {

    /**
     * ============================================================
     * @Insert
     * ============================================================
     *
     * Insert يعني:
     * إضافة بيانات جديدة
     * إلى قاعدة البيانات.
     *
     * عندما أرسل UserFood
     * إلى هذه الدالة،
     * يقوم Room بإضافته
     * داخل جدول user_food_table.
     */

    /**
     * ============================================================
     * insert
     * ============================================================
     *
     * هذه الدالة تضيف
     * طعام جديد
     * إلى قاعدة البيانات.
     *
     * استخدمتها عندما يقوم المستخدم
     * بإضافة طعام جديد
     * داخل التطبيق.
     *
     * @param userFood الطعام المراد إضافته
     */
    @Insert
    void insert(UserFood userFood);

    /**
     * ============================================================
     * @Query
     * ============================================================
     *
     * Query تعني:
     * تنفيذ أمر SQL
     * على قاعدة البيانات.
     *
     * استخدمتها لجلب البيانات
     * أو حذفها.
     */

    /**
     * ============================================================
     * getAll
     * ============================================================
     *
     * هذه الدالة تجلب
     * جميع الأطعمة
     * الموجودة داخل الجدول.
     *
     * SQL:
     * SELECT * FROM user_food_table
     *
     * معناها:
     * جلب جميع الصفوف
     * من جدول user_food_table.
     *
     * ORDER BY id DESC:
     * تعني ترتيب العناصر
     * من الأحدث إلى الأقدم.
     *
     * استخدمتها لعرض
     * سجل الطعام داخل RecyclerView.
     *
     * @return قائمة جميع الأطعمة
     */
    @Query("SELECT * FROM user_food_table ORDER BY id DESC")
    List<UserFood> getAll();

    /**
     * ============================================================
     * deleteFoodById
     * ============================================================
     *
     * هذه الدالة تحذف
     * طعام معين
     * باستخدام id الخاص به.
     *
     * SQL:
     * DELETE FROM user_food_table WHERE id = :foodId
     *
     * معناها:
     * حذف الصف الذي يملك
     * نفس id المرسل.
     *
     * :foodId يعني:
     * قيمة يتم إرسالها
     * من Parameter الدالة.
     *
     * استخدمتها عندما يضغط المستخدم
     * على زر Delete
     * لحذف عنصر من سجل الطعام.
     *
     * @param foodId معرف الطعام المراد حذفه
     */
    @Query("DELETE FROM user_food_table WHERE id = :foodId")
    void deleteFoodById(int foodId);
}