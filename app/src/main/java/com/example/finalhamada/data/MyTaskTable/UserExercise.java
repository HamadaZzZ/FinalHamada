package com.example.finalhamada.data.MyTaskTable; // مكان الكلاس داخل المشروع

import androidx.annotation.NonNull; // يعني أن القيمة لا يجب أن تكون null
import androidx.room.Entity; // يستخدم لتحويل الكلاس إلى Table داخل Room Database
import androidx.room.PrimaryKey; // يستخدم لتحديد المفتاح الأساسي داخل الجدول

/**
 * ============================================================
 * UserExercise
 * ============================================================
 *
 * هذا الكلاس يمثل تمرين للمستخدم
 * يتم تخزينه داخل Room Database.
 *
 * وظيفته الأساسية:
 * حفظ جميع بيانات التمرين مثل:
 * - الاسم
 * - الفئة
 * - التكرارات
 * - المجموعات
 * - الوزن
 * - مدة التمرين
 * - السعرات
 * - الملاحظات
 * - صورة التمرين
 *
 * أهمية هذا الكلاس:
 * استخدمته كـ Entity داخل قاعدة البيانات،
 * حتى يتم حفظ التمارين واسترجاعها
 * بشكل منظم داخل التطبيق.
 */
@Entity(tableName = "user_exercises")
public class UserExercise {

    /**
     * ============================================================
     * id
     * ============================================================
     *
     * هذا المتغير يمثل المعرف الفريد
     * لكل تمرين داخل قاعدة البيانات.
     *
     * PrimaryKey:
     * يعني أن هذا الحقل هو المفتاح الأساسي.
     *
     * autoGenerate = true:
     * يعني أن Room يقوم بإنشاء id تلقائيًا
     * لكل تمرين جديد.
     */
    @PrimaryKey(autoGenerate = true)
    private int id;

    /**
     * ============================================================
     * name
     * ============================================================
     *
     * يخزن اسم التمرين.
     *
     * أمثلة:
     * - Bench Press
     * - Push Up
     * - Squat
     */
    private String name;

    /**
     * ============================================================
     * category
     * ============================================================
     *
     * يخزن نوع أو فئة التمرين.
     *
     * أمثلة:
     * - Cardio
     * - Strength
     * - Chest
     */
    private String category;

    /**
     * ============================================================
     * reps
     * ============================================================
     *
     * يخزن عدد التكرارات
     * الخاصة بالتمرين.
     */
    private int reps;

    /**
     * ============================================================
     * sets
     * ============================================================
     *
     * يخزن عدد المجموعات
     * الخاصة بالتمرين.
     */
    private int sets;

    /**
     * ============================================================
     * weight
     * ============================================================
     *
     * يخزن الوزن المستخدم
     * أثناء التمرين.
     */
    private int weight;

    /**
     * ============================================================
     * duration
     * ============================================================
     *
     * يخزن مدة التمرين
     * بالدقائق.
     */
    private int duration;

    /**
     * ============================================================
     * calories
     * ============================================================
     *
     * يخزن عدد السعرات الحرارية
     * التي تم حرقها أثناء التمرين.
     */
    private int calories;

    /**
     * ============================================================
     * note
     * ============================================================
     *
     * يخزن ملاحظات إضافية
     * يكتبها المستخدم.
     */
    private String note;

    /**
     * ============================================================
     * imageRes
     * ============================================================
     *
     * يخزن صورة التمرين
     * على شكل Resource ID.
     *
     * استخدمته لعرض صورة
     * خاصة بكل تمرين داخل RecyclerView.
     */
    private int imageRes;

    /**
     * ============================================================
     * Constructor
     * ============================================================
     *
     * هذه الدالة تعمل عند إنشاء
     * تمرين جديد.
     *
     * تستقبل جميع بيانات التمرين
     * وتحفظها داخل الكائن.
     *
     * @param name اسم التمرين
     * @param category فئة التمرين
     * @param reps عدد التكرارات
     * @param sets عدد المجموعات
     * @param weight الوزن المستخدم
     * @param duration مدة التمرين
     * @param calories السعرات المحروقة
     * @param note ملاحظات إضافية
     * @param imageRes صورة التمرين
     */
    public UserExercise(
            String name,
            String category,
            int reps,
            int sets,
            int weight,
            int duration,
            int calories,
            String note,
            int imageRes
    ) {

        /**
         * حفظ اسم التمرين.
         */
        this.name = name;

        /**
         * حفظ فئة التمرين.
         */
        this.category = category;

        /**
         * حفظ عدد التكرارات.
         */
        this.reps = reps;

        /**
         * حفظ عدد المجموعات.
         */
        this.sets = sets;

        /**
         * حفظ الوزن المستخدم.
         */
        this.weight = weight;

        /**
         * حفظ مدة التمرين.
         */
        this.duration = duration;

        /**
         * حفظ السعرات المحروقة.
         */
        this.calories = calories;

        /**
         * حفظ الملاحظات.
         */
        this.note = note;

        /**
         * حفظ صورة التمرين.
         */
        this.imageRes = imageRes;
    }

    // ============================================================
    // Getters & Setters
    // ============================================================

    /**
     * ============================================================
     * getId
     * ============================================================
     *
     * ترجع id الخاص بالتمرين.
     *
     * @return id التمرين
     */
    public int getId() {
        return id;
    }

    /**
     * ============================================================
     * setId
     * ============================================================
     *
     * تستخدم لتعديل id التمرين.
     *
     * @param id القيمة الجديدة
     */
    public void setId(int id) {
        this.id = id;
    }

    /**
     * ============================================================
     * getName
     * ============================================================
     *
     * ترجع اسم التمرين.
     *
     * @return اسم التمرين
     */
    public String getName() {
        return name;
    }

    /**
     * ============================================================
     * setName
     * ============================================================
     *
     * تستخدم لتعديل اسم التمرين.
     *
     * @param name الاسم الجديد
     */
    public void setName(String name) {
        this.name = name;
    }

    /**
     * ============================================================
     * getCategory
     * ============================================================
     *
     * ترجع فئة التمرين.
     *
     * @return فئة التمرين
     */
    public String getCategory() {
        return category;
    }

    /**
     * ============================================================
     * setCategory
     * ============================================================
     *
     * تستخدم لتعديل فئة التمرين.
     *
     * @param category الفئة الجديدة
     */
    public void setCategory(String category) {
        this.category = category;
    }

    /**
     * ============================================================
     * getReps
     * ============================================================
     *
     * ترجع عدد التكرارات.
     *
     * @return عدد التكرارات
     */
    public int getReps() {
        return reps;
    }

    /**
     * ============================================================
     * setReps
     * ============================================================
     *
     * تستخدم لتعديل عدد التكرارات.
     *
     * @param reps القيمة الجديدة
     */
    public void setReps(int reps) {
        this.reps = reps;
    }

    /**
     * ============================================================
     * getSets
     * ============================================================
     *
     * ترجع عدد المجموعات.
     *
     * @return عدد المجموعات
     */
    public int getSets() {
        return sets;
    }

    /**
     * ============================================================
     * setSets
     * ============================================================
     *
     * تستخدم لتعديل عدد المجموعات.
     *
     * @param sets القيمة الجديدة
     */
    public void setSets(int sets) {
        this.sets = sets;
    }

    /**
     * ============================================================
     * getWeight
     * ============================================================
     *
     * ترجع الوزن المستخدم.
     *
     * @return الوزن المستخدم
     */
    public int getWeight() {
        return weight;
    }

    /**
     * ============================================================
     * setWeight
     * ============================================================
     *
     * تستخدم لتعديل الوزن المستخدم.
     *
     * @param weight القيمة الجديدة
     */
    public void setWeight(int weight) {
        this.weight = weight;
    }

    /**
     * ============================================================
     * getDuration
     * ============================================================
     *
     * ترجع مدة التمرين.
     *
     * @return مدة التمرين
     */
    public int getDuration() {
        return duration;
    }

    /**
     * ============================================================
     * setDuration
     * ============================================================
     *
     * تستخدم لتعديل مدة التمرين.
     *
     * @param duration القيمة الجديدة
     */
    public void setDuration(int duration) {
        this.duration = duration;
    }

    /**
     * ============================================================
     * getCalories
     * ============================================================
     *
     * ترجع السعرات المحروقة.
     *
     * @return السعرات المحروقة
     */
    public int getCalories() {
        return calories;
    }

    /**
     * ============================================================
     * setCalories
     * ============================================================
     *
     * تستخدم لتعديل السعرات المحروقة.
     *
     * @param calories القيمة الجديدة
     */
    public void setCalories(int calories) {
        this.calories = calories;
    }

    /**
     * ============================================================
     * getNote
     * ============================================================
     *
     * ترجع الملاحظات الخاصة بالتمرين.
     *
     * @return الملاحظات
     */
    public String getNote() {
        return note;
    }

    /**
     * ============================================================
     * setNote
     * ============================================================
     *
     * تستخدم لتعديل الملاحظات.
     *
     * @param note الملاحظة الجديدة
     */
    public void setNote(String note) {
        this.note = note;
    }

    /**
     * ============================================================
     * getImageRes
     * ============================================================
     *
     * ترجع صورة التمرين.
     *
     * @return Resource ID للصورة
     */
    public int getImageRes() {
        return imageRes;
    }

    /**
     * ============================================================
     * setImageRes
     * ============================================================
     *
     * تستخدم لتعديل صورة التمرين.
     *
     * @param imageRes الصورة الجديدة
     */
    public void setImageRes(int imageRes) {
        this.imageRes = imageRes;
    }

    /**
     * ============================================================
     * toString
     * ============================================================
     *
     * تحول بيانات الكائن
     * إلى String نصي.
     *
     * استخدمتها لأغراض:
     * - الطباعة
     * - Logcat
     * - Debugging
     *
     * @return تمثيل نصي للتمرين
     */
    @NonNull
    @Override
    public String toString() {

        return "UserExercise{" +
                "id=" + id +
                ", name='" + name + '\'' +
                ", category='" + category + '\'' +
                ", reps=" + reps +
                ", sets=" + sets +
                ", weight=" + weight +
                ", duration=" + duration +
                ", calories=" + calories +
                ", note='" + note + '\'' +
                ", imageRes=" + imageRes +
                '}';
    }
}