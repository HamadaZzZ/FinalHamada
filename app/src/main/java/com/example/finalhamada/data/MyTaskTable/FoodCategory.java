package com.example.finalhamada.data.MyTaskTable; // مكان الكلاس داخل المشروع

import java.util.List; // يستخدم لتخزين قائمة من العناصر

/**
 * ============================================================
 * FoodCategory
 * ============================================================
 *
 * هذا الكلاس يمثل فئة (Category)
 * من الأطعمة داخل التطبيق.
 *
 * وظيفته الأساسية:
 * تنظيم الأطعمة إلى مجموعات مرتبة
 * مثل:
 * - Protein
 * - Carbs
 * - Drinks
 *
 * أهمية هذا الكلاس:
 * بدل عرض جميع الأطعمة
 * داخل قائمة طويلة وعشوائية،
 * قمت بتقسيمها إلى Categories
 * حتى تصبح الواجهة أوضح وأسهل للمستخدم.
 *
 * استخدمته مع RecyclerView
 * داخل FoodListFragment
 * لإنشاء قائمة قابلة للفتح والإغلاق.
 */
public class FoodCategory {

    /**
     * ============================================================
     * title
     * ============================================================
     *
     * هذا المتغير يخزن اسم الفئة.
     *
     * أمثلة:
     * - Protein
     * - Carbs
     * - Drinks
     *
     * استخدمته لعرض عنوان القسم
     * داخل RecyclerView.
     */
    private String title;

    /**
     * ============================================================
     * foodItems
     * ============================================================
     *
     * هذه القائمة تحتوي على
     * جميع الأطعمة التابعة للفئة.
     *
     * كل عنصر داخلها
     * هو كائن من نوع UserFood.
     *
     * استخدمتها حتى كل Category
     * تحتوي الأطعمة الخاصة بها فقط.
     */
    private List<UserFood> foodItems;

    /**
     * ============================================================
     * isExpanded
     * ============================================================
     *
     * هذا المتغير يحدد
     * إذا كانت الفئة مفتوحة أو مغلقة.
     *
     * إذا كانت true:
     * يتم إظهار الأطعمة داخل القسم.
     *
     * إذا كانت false:
     * يتم إخفاء الأطعمة.
     *
     * استخدمته لإنشاء
     * Expandable RecyclerView.
     */
    private boolean isExpanded;

    /**
     * ============================================================
     * Constructor
     * ============================================================
     *
     * هذه الدالة تعمل عند إنشاء
     * FoodCategory جديد.
     *
     * تستقبل:
     * - اسم الفئة
     * - قائمة الأطعمة
     * - حالة الفتح أو الإغلاق
     *
     * @param title اسم الفئة
     * @param foodItems قائمة الأطعمة التابعة للفئة
     * @param isExpanded حالة الفئة (مفتوحة أو مغلقة)
     */
    public FoodCategory(
            String title,
            List<UserFood> foodItems,
            boolean isExpanded
    ) {

        /**
         * حفظ اسم الفئة.
         */
        this.title = title;

        /**
         * حفظ قائمة الأطعمة.
         */
        this.foodItems = foodItems;

        /**
         * حفظ حالة الفئة.
         */
        this.isExpanded = isExpanded;
    }

    /**
     * ============================================================
     * getTitle
     * ============================================================
     *
     * ترجع اسم الفئة.
     *
     * استخدمتها لعرض
     * عنوان القسم داخل الواجهة.
     *
     * @return اسم الفئة
     */
    public String getTitle() {
        return title;
    }

    /**
     * ============================================================
     * getFoodItems
     * ============================================================
     *
     * ترجع قائمة الأطعمة
     * الخاصة بهذه الفئة.
     *
     * استخدمتها لعرض
     * الأطعمة داخل Category معين.
     *
     * @return قائمة الأطعمة
     */
    public List<UserFood> getFoodItems() {
        return foodItems;
    }

    /**
     * ============================================================
     * isExpanded
     * ============================================================
     *
     * تتحقق إذا كانت الفئة
     * مفتوحة أو مغلقة.
     *
     * استخدمتها لمعرفة:
     * هل يجب إظهار الأطعمة
     * أو إخفاؤها داخل RecyclerView.
     *
     * @return true إذا كانت مفتوحة
     */
    public boolean isExpanded() {
        return isExpanded;
    }

    /**
     * ============================================================
     * setExpanded
     * ============================================================
     *
     * تستخدم لتغيير حالة الفئة.
     *
     * عند ضغط المستخدم
     * على Category Header،
     * يتم استخدام هذه الدالة
     * لفتح أو إغلاق القسم.
     *
     * @param expanded القيمة الجديدة للحالة
     */
    public void setExpanded(boolean expanded) {

        /**
         * تحديث حالة الفئة.
         */
        isExpanded = expanded;
    }
}