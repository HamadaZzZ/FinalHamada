package com.example.finalhamada.data.MyTaskTable; // مكان الواجهة داخل المشروع

import androidx.room.Dao; // يحول الواجهة إلى DAO داخل Room Database
import androidx.room.Delete; // يستخدم لحذف بيانات من الجدول
import androidx.room.Insert; // يستخدم لإضافة بيانات إلى الجدول
import androidx.room.Query; // يستخدم لتنفيذ SQL Query
import androidx.room.Update; // يستخدم لتعديل بيانات موجودة

import java.util.List; // لتخزين قائمة عناصر

/**
 * ============================================================
 * UserExerciseQuery
 * ============================================================
 *
 * هذه الواجهة تعتبر DAO
 * الخاصة بجدول user_exercises.
 *
 * DAO اختصار لـ:
 * Data Access Object
 *
 * يعني:
 * كلاس أو Interface
 * مسؤول عن التواصل مع قاعدة البيانات.
 *
 * أهمية DAO:
 * بدل كتابة أوامر SQL يدويًا
 * في كل مكان داخل المشروع،
 * نقوم بجمع جميع عمليات قاعدة البيانات
 * داخل Interface واحدة منظمة.
 *
 * استخدمت هذا DAO للتعامل مع:
 * - إضافة تمرين
 * - تعديل تمرين
 * - حذف تمرين
 * - جلب التمارين
 * - البحث عن تمرين
 *
 * Room يقوم تلقائيًا
 * بتحويل هذه الدوال
 * إلى SQL Queries حقيقية.
 */
@Dao
public interface UserExerciseQuery {

    /**
     * ============================================================
     * @Insert
     * ============================================================
     *
     * Insert يعني:
     * إضافة بيانات جديدة
     * إلى قاعدة البيانات.
     *
     * عندما أرسل UserExercise
     * إلى هذه الدالة،
     * يقوم Room بإضافة التمرين
     * داخل جدول user_exercises.
     */

    /**
     * ============================================================
     * insert
     * ============================================================
     *
     * هذه الدالة تضيف تمرين جديد
     * إلى قاعدة البيانات.
     *
     * استخدمتها عندما يقوم المستخدم
     * بإضافة تمرين جديد من التطبيق.
     *
     * @param userExercise التمرين المراد إضافته
     *
     * @return id الذي تم إنشاؤه تلقائيًا
     */
    @Insert
    long insert(UserExercise userExercise);

    /**
     * ============================================================
     * @Update
     * ============================================================
     *
     * Update يعني:
     * تعديل بيانات موجودة مسبقًا
     * داخل قاعدة البيانات.
     *
     * يستخدم عندما يكون العنصر موجود
     * ونريد تغيير بياناته.
     */

    /**
     * ============================================================
     * update
     * ============================================================
     *
     * هذه الدالة تعدل تمرين موجود
     * داخل قاعدة البيانات.
     *
     * استخدمتها عندما يقوم المستخدم
     * بتعديل بيانات تمرين موجود.
     *
     * @param userExercise التمرين بعد التعديل
     */
    @Update
    void update(UserExercise userExercise);

    /**
     * ============================================================
     * @Delete
     * ============================================================
     *
     * Delete يعني:
     * حذف بيانات من قاعدة البيانات.
     *
     * يستخدم لإزالة عنصر موجود
     * من الجدول.
     */

    /**
     * ============================================================
     * delete
     * ============================================================
     *
     * هذه الدالة تحذف تمرين
     * من قاعدة البيانات.
     *
     * استخدمتها عندما يضغط المستخدم
     * على زر Delete.
     *
     * @param userExercise التمرين المراد حذفه
     */
    @Delete
    void delete(UserExercise userExercise);

    /**
     * ============================================================
     * @Query
     * ============================================================
     *
     * Query تعني:
     * تنفيذ أمر SQL
     * على قاعدة البيانات.
     *
     * استخدمتها لجلب البيانات
     * أو حذفها أو البحث عنها.
     */

    /**
     * ============================================================
     * getAllExercises
     * ============================================================
     *
     * هذه الدالة تجلب
     * جميع التمارين
     * الموجودة داخل الجدول.
     *
     * SQL:
     * SELECT * FROM user_exercises
     *
     * معناها:
     * جلب كل الأعمدة
     * من جدول user_exercises.
     *
     * استخدمتها لعرض جميع التمارين
     * داخل RecyclerView.
     *
     * @return قائمة جميع التمارين
     */
    @Query("SELECT * FROM user_exercises")
    List<UserExercise> getAllExercises();

    /**
     * ============================================================
     * getExerciseById
     * ============================================================
     *
     * هذه الدالة تجلب تمرين واحد
     * باستخدام id الخاص به.
     *
     * SQL:
     * WHERE id = :id
     *
     * معناها:
     * ابحث عن التمرين
     * الذي يملك نفس id المرسل.
     *
     * :id يعني:
     * قيمة يتم إرسالها
     * من Parameter الدالة.
     *
     * استخدمتها عندما أحتاج
     * جلب تمرين معين فقط.
     *
     * @param id معرف التمرين
     *
     * @return التمرين المطلوب
     */
    @Query("SELECT * FROM user_exercises WHERE id = :id")
    UserExercise getExerciseById(int id);

    /**
     * ============================================================
     * deleteAllExercises
     * ============================================================
     *
     * هذه الدالة تحذف
     * جميع التمارين
     * من الجدول.
     *
     * SQL:
     * DELETE FROM user_exercises
     *
     * معناها:
     * حذف كل الصفوف
     * داخل الجدول.
     *
     * استخدمتها مثلًا
     * لإعادة تعيين البيانات.
     */
    @Query("DELETE FROM user_exercises")
    void deleteAllExercises();

    /**
     * ============================================================
     * getExercisesByCategory
     * ============================================================
     *
     * هذه الدالة تجلب
     * جميع التمارين
     * التابعة لفئة معينة.
     *
     * مثال:
     * - Cardio
     * - Strength
     *
     * SQL:
     * WHERE category = :category
     *
     * معناها:
     * جلب جميع التمارين
     * التي تساوي فئتها
     * القيمة المرسلة.
     */
    @Query("SELECT * FROM user_exercises WHERE category = :category")
    List<UserExercise> getExercisesByCategory(String category);

}